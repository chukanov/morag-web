#!/bin/bash
# Транскрибация записей через generic-клиент morag. ШАБЛОН: скопируйте в каталог семьи корпуса
# (рядом с asr-profile.env и inbox/) — пути ниже считаются от него.
#
#   ./transcribe.sh --dry              # только показать, что будет расшифровано
#   ./transcribe.sh                    # прогнать всё, что лежит в inbox/
#   ./transcribe.sh /путь/к/каталогу [--dry]      # прогнать другой каталог
#
# Кладите видео и аудио в corpora/<семья>/inbox/ — клиент найдёт их сам (mp4, mkv, mov, webm, avi,
# m4v, mp3, m4a, wav, aac, ogg, opus, flac) и вынет звуковую дорожку через ffmpeg. Результат
# ложится РЯДОМ с исходником: «Планёрка 12 марта.mp4» → «Планёрка 12 марта.{md,json}».
# Дальше запись собирается в каталог корпуса: tools/make_record.py (см. README).
#
# Идемпотентно (файл с готовым .json пропускается) и строго последовательно: реестр голосов
# общий, параллельный прогон разъедет нумерацию Speaker_N.
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
MORAG_REPO="${MORAG_REPO:-$HERE/../../../morag}"
CLIENT="$MORAG_REPO/services/asr-adaptor/client/run_folder.sh"
[ -f "$CLIENT" ] || { echo "morag не найден: $MORAG_REPO (задайте MORAG_REPO)"; exit 1; }

export ASR_BASE="${ASR_BASE:-http://127.0.0.1:8082}"

# Каталог первым аргументом — иначе inbox. Чужой каталог гоняем, когда надо сверить прогон после
# правки конвейера, не подмешивая записи в рабочую очередь.
# ⚠️ Аргумент, который не каталог и не флаг, — это ошибка, а не повод молча взять inbox.
# Ловилось на себе: относительный путь из чужого рабочего каталога уехал в inbox, прогон
# отчитался «записей не нашлось», и выглядело это как пустая очередь, а не как опечатка.
case "${1:-}" in
  ""|--*) DIR="$HERE/inbox" ;;
  *)
    [ -d "$1" ] || { echo "не каталог: $1"; exit 2; }
    DIR="$(cd "$1" && pwd)"; shift ;;
esac
mkdir -p "$DIR"

# Стек должен быть поднят. Проверяем ДО прогона: без этого падение выглядит как ошибка клиента,
# а на деле стек просто не запущен (или диаризатор ещё грузит модель — это ~90 секунд).
if ! HEALTH="$(curl -fsS --max-time 5 "$ASR_BASE/health" 2>/dev/null)"; then
  echo "адаптер не отвечает на $ASR_BASE/health — поднимите стек:"
  echo "  ASR_STACK_ENV=~/.asr-stack.env $MORAG_REPO/services/asr-adaptor/deploy/mac/stack.sh up"
  exit 1
fi
echo "=== адаптер: $HEALTH"
# ⚠️ Профиль корпуса (ASR_CORPUS_DESC и прочее) читает процесс адаптера при старте, и наружу он
# его не показывает. Если правили asr-profile.env — стек надо было перезапустить, иначе прогон
# пойдёт со СТАРЫМИ промптами и будет выглядеть удавшимся.

echo "=== каталог: $DIR"
bash "$CLIENT" "$DIR" "$@"
