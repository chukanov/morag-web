// «Магнит» облака: слово рядом с курсором чуть растёт и подтягивается к нему (владелец, 15.09 —
// «МО» в виде фильтров должно быть живым). Чистая арифметика здесь, DOM — в list.js.
//
// Правило одно на все слова: сила f = (1 − d/R)² — у курсора максимальна, к краю радиуса
// плавно гаснет. Рост — до +40 % кегля. Сдвиг — доля расстояния до курсора (55 %) × f:
// в пикселях он растёт с расстоянием, а сила при этом падает, и произведение даёт горб в
// середине радиуса — так выглядит поле магнита, а не «прилипание» к курсору. Под самым
// курсором сдвиг ноль: слово уже на месте, ему остаётся только вырасти.
// Подобрано на живом облаке (15.09): при доле 0.18 сдвиг выходил ~2 px и не читался вовсе;
// при 0.55 слово в середине радиуса подтягивается на ~8 px — видно, но не «прыгает под палец».
export const MAGNET = { radius: 100, shift: 0.55, grow: 0.4 };

export function pull(dx, dy, { radius = MAGNET.radius, shift = MAGNET.shift, grow = MAGNET.grow } = {}) {
  const d = Math.hypot(dx, dy);
  if (d >= radius) return { x: 0, y: 0, s: 1 };
  const f = (1 - d / radius) ** 2;
  return { x: dx * shift * f, y: dy * shift * f, s: 1 + grow * f };
}
