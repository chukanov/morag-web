"""Тесты идут по ДЕМО-корпусу, а не по тому, что лежит рядом на машине.

⚠️ Это не мелочь настройки, а условие, ради которого демо-корпус вообще существует.
`load_config()` подхватывает `app/config.yml`, если он есть, — и на машине владельца тесты
молча уезжали бы на рабочий корпус. Тогда проверка «приложение поднимается» зелена и там, где
без данных компании оно не поднимется вовсе, а именно это и предстоит будущей чистой репе.

Берём ровно тот файл, который лежит в git (`app/config.example.yml`): он же и есть обещание
«клонировал и запустил».
"""

from __future__ import annotations

import os
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
os.environ.setdefault("MORAG_WEB_CONFIG", str(REPO / "app" / "config.example.yml"))
